const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const PERSONA = fs.readFileSync(path.join(ROOT, 'training/persona/system_prompt.md'), 'utf8');
const names = require(path.join(ROOT, 'training/data/card_names_ko.json'));
const ALL_CARDS = require(path.join(ROOT, 'assets/tarot/cards.json'));
const CARD_ID_TO_NAME_EN = Object.fromEntries(ALL_CARDS.map(c => [c.id, c.name]));
const OW = { upright: '정방향', reversed: '역방향' };

function cardObj(id, orientation) {
  return { id, name: names[id] || CARD_ID_TO_NAME_EN[id], orientation };
}
function tag(cardSpecs) {
  const cs = cardSpecs.map(([id, o]) => cardObj(id, o));
  return { cards: cs, tagText: `[뽑힌 카드: ${cs.map(c => `${c.name}(${OW[c.orientation]})`).join(', ')}]` };
}
function buildMessages(cardSpecs, turnsFlat) {
  const { cards, tagText } = tag(cardSpecs);
  const messages = [{ role: 'system', content: PERSONA }];
  const flat = [...turnsFlat];
  flat[0] = `${tagText}\n${flat[0]}`;
  for (let i = 0; i < flat.length; i += 2) {
    messages.push({ role: 'user', content: flat[i] });
    messages.push({ role: 'assistant', content: flat[i + 1] });
  }
  return { cards, messages };
}
function makeRec(id, topic, turn_count, cardSpecs, turnsFlat) {
  const { cards, messages } = buildMessages(cardSpecs, turnsFlat);
  return { id, language: 'ko', topic, turn_count, cards, messages };
}

