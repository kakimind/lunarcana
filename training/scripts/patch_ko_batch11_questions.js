let patched = 0;
for (const r of recs) {
  if (patches[r.id]) {
    r.messages[r.messages.length - 1].content = patches[r.id];
    patched++;
  }
}

fs.writeFileSync(path, recs.map(r => JSON.stringify(r)).join('\n') + '\n');
