const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const FILE = path.join(ROOT, 'training/data/pilot/ko.jsonl');
const SYS = fs.readFileSync(path.join(ROOT, 'training/scripts/_sysprompt_cache.txt'), 'utf8');

function tag(card) {
  return `[뽑힌 카드: ${card.name}(${card.orientation === 'upright' ? '정방향' : '역방향'})]`;
}

function build(id, topic, cards, turns) {
  const messages = [{ role: 'system', content: SYS }, ...turns];
  const turn_count = (messages.length - 1) / 2;
  return { id, language: 'ko', topic, turn_count, cards, messages };
}

function u(text) { return { role: 'user', content: text }; }
function a(text) { return { role: 'assistant', content: text }; }

